// Embeds /samples (queries + their schemas) into src/generated/samples.js so the browser app and
// the single-file build can open them without fetching. Run: npm run generate (CI checks it is current).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'samples');
const index = JSON.parse(fs.readFileSync(path.join(dir, 'index.json'), 'utf8'));
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
const samples = index.map((s) => ({ ...s, sql: read(s.file), schemaText: s.schema ? read(s.schema) : null, schemaName: s.schema ? path.basename(s.schema) : null }));
const out = `// AUTO-GENERATED by scripts/generate.mjs - do not edit. Run \`npm run generate\`.\nexport const SAMPLES = ${JSON.stringify(samples)};\n`;
const target = path.join(root, 'src/generated/samples.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) { console.error('src/generated/samples.js is stale. Run `npm run generate` and commit.'); process.exit(1); }
  console.log('generated files up to date');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, out);
  console.log(`wrote src/generated/samples.js (${samples.length} samples)`);
}
