// Markdown and JSON exports of an analysis (used by the Export tab and the CLI).
import { VERSION } from './index.js';

export const HOMEPAGE = 'https://github.com/adityakilari/any-query';

const plain = (s) => String(s || '');

export function toMarkdown(result, options = {}) {
  const L = [];
  const title = options.title || 'Query explanation';
  L.push(`# ${title}`, '');
  L.push(`_Generated by [Any Query](${HOMEPAGE}) ${VERSION} · ${result.dialect.label}${result.schema ? ` · schema: ${result.schema.fileName}` : ''}_`, '');
  const multi = result.statements.length > 1;
  result.statements.forEach((st, i) => {
    const h = multi ? '##' : '##';
    if (multi) L.push(`## ${i + 1}. ${st.title} (line ${st.line})`, '');
    L.push(`${h}${multi ? '#' : ''} Summary`, '');
    for (const s of st.summary) L.push(`- ${plain(s)}`);
    L.push('');
    if (st.type === 'routine') {
      const R = st.routine;
      if (R.params.length) {
        L.push('| Parameter | Direction | Type | Default |', '|---|---|---|---|');
        for (const p of R.params) L.push(`| \`${p.name}\` | ${p.mode || 'IN'} | \`${cell(p.type)}\` | ${p.default ? `\`${cell(p.default)}\`` : ''} |`);
        L.push('');
      }
      L.push(`${h}${multi ? '#' : ''} What it does`, '');
      const walk = (items, depth) => {
        for (const o of items) {
          const pad = '  '.repeat(depth);
          if (o.branches) { for (const b of o.branches) { L.push(`${pad}- **${plain(b.text)}** _(line ${b.line || o.line})_`); walk(b.children, depth + 1); } continue; }
          L.push(`${pad}- ${o.loop || o.k === 'handler' ? `**${plain(o.text)}**` : plain(o.text)} _(line ${o.line})_`);
          for (const it of o.items || []) L.push(`${pad}  - ${plain(it.text)}`);
          if (o.children) walk(o.children, depth + 1);
        }
      };
      walk(st.outline, 0);
      L.push('');
    }
    if (st.steps && st.steps.length) {
      L.push(`${h}${multi ? '#' : ''} Step by step`, '');
      for (const step of st.steps) {
        L.push(`**Step ${step.n}: ${plain(step.title)}**`, '');
        for (const line of step.lines) {
          L.push(`- ${plain(line.text)}`);
          for (const it of line.items || []) L.push(`  - ${plain(it.text)}`);
        }
        L.push('');
      }
    }
    if (st.outputs && st.outputs.length) {
      L.push(`${h}${multi ? '#' : ''} Columns returned`, '');
      L.push('| Column | Meaning | Comes from |', '|---|---|---|');
      for (const o of st.outputs) L.push(`| \`${o.name}\` | ${cell(o.text)}${o.detail ? ` ${cell(o.detail)}` : ''} | ${o.origins && o.origins.length ? o.origins.map((x) => `\`${x}\``).join(', ') : ''} |`);
      L.push('');
    }
    if (st.tables && st.tables.length) {
      L.push(`${h}${multi ? '#' : ''} Tables used`, '');
      for (const t of st.tables) L.push(`- \`${t.name}\`${t.aliases.length ? ` (as ${t.aliases.map((a) => `\`${a}\``).join(', ')})` : ''}: ${t.allColumns ? 'all columns' : t.columns.map((c) => `\`${c}\``).join(', ') || 'no columns referenced'}${t.purpose ? `. ${cell(t.purpose)}` : ''}`);
      L.push('');
    }
    if (st.findings && st.findings.length) {
      L.push(`${h}${multi ? '#' : ''} Review`, '');
      for (const f of st.findings) {
        L.push(`- **${f.severity.toUpperCase()}** · line ${f.line}${f.step ? ` (${f.step})` : ''}: ${plain(f.title)}  `);
        L.push(`  ${plain(f.detail)}${f.fix ? `  ` : ''}`);
        if (f.fix) L.push(`  _Fix:_ ${plain(f.fix)}`);
      }
      L.push('');
    }
  });
  if (result.notes && result.notes.length) {
    L.push('## Notes', '');
    for (const n of result.notes) L.push(`- ${n.message}`);
    L.push('');
  }
  if (options.includeSql !== false) {
    L.push('## Formatted SQL', '', '```sql', result.formatted.trimEnd(), '```', '');
  }
  return L.join('\n');
}

export function stripRoutine(st) {
  if (st.type !== 'routine') return st;
  const clean = (items) => (items || []).map((o) => ({ ...o, sql: o.sql ? { s: o.sql.s, e: o.sql.e, line: o.sql.line, type: o.sql.type, summary: o.sql.summary } : undefined, items: o.items ? o.items.map((it) => ({ text: it.text, line: it.line })) : undefined, children: o.children ? clean(o.children) : undefined, branches: o.branches ? o.branches.map((b) => ({ ...b, children: clean(b.children) })) : undefined }));
  return { ...st, outline: clean(st.outline), embedded: (st.embedded || []).map(({ model, flow, ...e }) => { void model; void flow; return { ...e, steps: (e.steps || []).map(({ block, ...x }) => { void block; return { ...x, lines: x.lines.map(({ node, ...l }) => { void node; return l; }) }; }) }; }) };
}

function cell(s) { return plain(s).replace(/\|/g, '\\|').replace(/\n/g, ' '); }

export function toJson(result) {
  const strip = (st) => {
    const { model, flow, ...rest } = st;
    void model;
    return {
      ...rest,
      steps: (rest.steps || []).map(({ block, ...s }) => { void block; return { ...s, lines: s.lines.map(({ node, ...l }) => { void node; return l; }) }; }),
      flow,
    };
  };
  return JSON.stringify({ ...result, statements: result.statements.map((st) => strip(stripRoutine(st))) }, (k, v) => (k === 'target' && v && v.source ? { name: v.name, kind: v.kind } : k === 'table' && v && v.colMap ? v.name : v), 2);
}
